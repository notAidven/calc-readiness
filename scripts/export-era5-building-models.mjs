/** Bundle the app's Three.js and GLTFExporter for browser evaluation. */
function threeBundle() {
  const dir = mkdtempSync(join(tmpdir(), "era5-three-bundle-"));
  const entry = join(dir, "three-entry.js");
  const out = join(dir, "three-bundle.js");
  writeFileSync(
    entry,
    [
      'import * as THREE from "three";',
      'import { GLTFExporter } from "three/examples/jsm/exporters/GLTFExporter.js";',
      "window.THREE = THREE;",
      "window.GLTFExporter = GLTFExporter;",
      "",
    ].join("\n"),
  );
  const esbuild = join(ROOT, "node_modules/.bin/esbuild");
  if (!existsSync(esbuild)) {
    throw new Error("esbuild not installed — run `npm install` at the repo root");
  }
  execFileSync(
    esbuild,
    [entry, "--bundle", "--format=iife", `--outfile=${out}`, "--log-level=warning"],
    { env: { ...process.env, NODE_PATH: join(ROOT, "node_modules") } },
  );
  return out;
}

function assertUncommittedPopulation(jobs) {
  const expected = jobs
    .filter((job) => !job.committed)
    .map((job) => job.name)
    .sort();
  const declared = Object.keys(UNCOMMITTED_DIGESTS).sort();
  if (expected.length !== 10 || JSON.stringify(expected) !== JSON.stringify(declared)) {
    throw new Error(
      `uncommitted digest population does not match the ten civic/hub early phases:\n` +
        `expected ${expected.join(", ")}\n` +
        `declared ${declared.join(", ")}`,
    );
  }
}

function assertBuildingPopulation() {
  const art = BUILDINGS.map((building) => building.art);
  const targets = BUILDINGS.map((building) => `${building.kind}:${building.id}`);
  const counts = {
    skill: BUILDINGS.filter((building) => building.kind === "skill").length,
    civic: BUILDINGS.filter((building) => building.kind === "civic").length,
    townhall: BUILDINGS.filter((building) => building.kind === "townhall").length,
  };
  if (
    BUILDINGS.length !== 10 ||
    new Set(art).size !== 10 ||
    new Set(targets).size !== 10 ||
    counts.skill !== 5 ||
    counts.civic !== 4 ||
    counts.townhall !== 1
  ) {
    throw new Error(
      `Era 5 mapping must be ten unique source keys and targets in a 5 skill + 4 civic + 1 hub partition`,
    );
  }
}

function parseArgs(argv) {
  const seen = new Set();
  let check = false;
  let all = false;
  let seeded = true;
  let out = null;

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (!["--check", "--all", "--no-seed", "--out"].includes(arg)) {
      throw new Error(`Unknown exporter argument: ${JSON.stringify(arg)}`);
    }
    if (seen.has(arg)) {
      throw new Error(`Duplicate exporter flag: ${arg}`);
    }
    seen.add(arg);

    switch (arg) {
      case "--check":
        check = true;
        break;
      case "--all":
        all = true;
        break;
      case "--no-seed":
        seeded = false;
        break;
      default: {
        const value = argv[index + 1];
        if (typeof value !== "string" || value.trim() === "" || value.startsWith("--")) {
          throw new Error("--out requires one non-empty path value");
        }
        out = value.trim();
        index += 1;
      }
    }
  }

  if (!seeded && !check) {
    throw new Error(
      "--no-seed requires --check so random bytes can never overwrite assets",
    );
  }
  if (all && !out && !check) {
    throw new Error(
      "--all requires --out so deliberately unbundled stages stay out of the tree",
    );
  }
  if (check && all) {
    throw new Error(
      "--check already verifies all stages and cannot be combined with --all",
    );
  }
  if (check && out) {
    throw new Error(
      "--check owns an isolated temp output and cannot be combined with --out",
    );
  }

  return { check, all: all || check, seeded, out };
}

function physicalPath(candidate) {
  const suffix = [];
  let existing = resolve(candidate);
  while (!existsSync(existing)) {
    const parent = dirname(existing);
    if (parent === existing) {
      throw new Error(`Cannot resolve exporter output path: ${candidate}`);
    }
    suffix.unshift(basename(existing));
    existing = parent;
  }
  return resolve(realpathSync(existing), ...suffix);
}

function assertSafeCustomOut(out) {
  if (out === null) {
    return;
  }
  const productionModels = physicalPath(MODELS);
  const customOut = physicalPath(out);
  const fromProduction = relative(productionModels, customOut);
  const insideProduction =
    fromProduction === "" ||
    (!isAbsolute(fromProduction) &&
      fromProduction !== ".." &&
      !fromProduction.startsWith(`..${sep}`));
  if (insideProduction) {
    throw new Error(
      `Custom --out cannot resolve inside the production model tree: ${customOut}`,
    );
  }
}

function lstatOrNull(path) {
  try {
    return lstatSync(path);
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw error;
  }
}

function promotionTarget(job, customOut) {
  return customOut === null ? join(job.dir, job.name) : join(customOut, job.name);
}

/** Refuse a destination symlink itself; directory containment alone cannot see this case. */
function assertSafePlannedDestinations(jobs, customOut) {
  for (const job of jobs) {
    const target = promotionTarget(job, customOut);
    const stat = lstatOrNull(target);
    if (stat?.isSymbolicLink()) {
      throw new Error(`Refusing symlinked exporter destination file: ${target}`);
    }
    if (stat && !stat.isFile()) {
      throw new Error(`Exporter destination is not a regular file: ${target}`);
    }
  }
}

function validateGlb(bytes, name) {
  if (bytes.length < 20 || bytes.toString("ascii", 0, 4) !== "glTF") {
    throw new Error(`${name} is not a GLB`);
  }
  if (bytes.readUInt32LE(4) !== 2 || bytes.readUInt32LE(8) !== bytes.length) {
    throw new Error(`${name} is not a complete glTF 2 binary`);
  }
  const jsonLength = bytes.readUInt32LE(12);
  if (bytes.readUInt32LE(16) !== 0x4e4f534a || 20 + jsonLength > bytes.length) {
    throw new Error(`${name} has no valid JSON chunk`);
  }
  const json = JSON.parse(bytes.toString("utf8", 20, 20 + jsonLength).trim());
  if (!String(json.asset?.version ?? "").startsWith("2")) {
    throw new Error(`${name} JSON does not declare glTF 2`);
  }
  let nonemptyPositions = 0;
  for (const mesh of json.meshes ?? []) {
    for (const primitive of mesh.primitives ?? []) {
      const position = json.accessors?.[primitive.attributes?.POSITION];
      if (
        position?.min?.length === 3 &&
        position?.max?.length === 3 &&
        position.max.some((value, index) => value > position.min[index])
      ) {
        nonemptyPositions += 1;
      }
    }
  }
  if (nonemptyPositions === 0) {
    throw new Error(`${name} has no non-empty POSITION bounds`);
  }
}

function validateStagedOutputs(stageDir, jobs, seeded) {
  const expected = jobs.map((job) => job.name).sort();
  const actual = readdirSync(stageDir).sort();
  if (expected.length !== 30 || JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(
      `staged output census is not the exact thirty source stages:\n` +
        `expected ${expected.join(", ")}\nactual ${actual.join(", ")}`,
    );
  }

  for (const job of jobs) {
    const bytes = readFileSync(join(stageDir, job.name));
    validateGlb(bytes, job.name);
    if (!job.committed) {
      if (lstatOrNull(join(job.dir, job.name)) !== null) {
        throw new Error(`${job.name} is PRESENT in the tree but declared uncommitted`);
      }
      if (seeded) {
        const digest = createHash("sha256").update(bytes).digest("hex");
        if (UNCOMMITTED_DIGESTS[job.name] !== digest) {
          throw new Error(
            `${job.name} regenerated differently from its omitted-stage digest: ` +
              `expected ${UNCOMMITTED_DIGESTS[job.name] ?? "nothing"}, got ${digest}`,
          );
        }
      }
    }
  }
}

function promoteOutputs(stageDir, jobs, customOut) {
  const token = `${process.pid}-${Date.now()}`;
  const prepared = [];
  const promoted = [];
  try {
    assertSafePlannedDestinations(jobs, customOut);
    for (const job of jobs) {
      const target = promotionTarget(job, customOut);
      mkdirSync(dirname(target), { recursive: true });
      const original = lstatOrNull(target) ? readFileSync(target) : null;
      const next = join(dirname(target), `.${basename(target)}.era5-next-${token}`);
      if (lstatOrNull(next) !== null) {
        throw new Error(`Exporter promotion temp already exists: ${next}`);
      }
      writeFileSync(next, readFileSync(join(stageDir, job.name)), { flag: "wx" });
      prepared.push({ target, next, original });
    }
    for (const item of prepared) {
      renameSync(item.next, item.target);
      promoted.push(item);
    }
  } catch (error) {
    for (const item of prepared) {
      if (lstatOrNull(item.next) !== null) unlinkSync(item.next);
    }
    for (const item of [...promoted].reverse()) {
      if (item.original === null) {
        if (lstatOrNull(item.target) !== null) unlinkSync(item.target);
        continue;
      }
      const rollback = join(
        dirname(item.target),
        `.${basename(item.target)}.era5-rollback-${token}`,
      );
      writeFileSync(rollback, item.original, { flag: "wx" });
      renameSync(rollback, item.target);
    }
    throw error;
  }
}

function testInjection() {
  if (process.env.NODE_ENV !== "test") return null;
  const injection = process.env.ERA5_EXPORTER_TEST_INJECTION ?? null;
  if (
    injection !== null &&
    !["mid-run-error", "post-run-warning", "post-run-error"].includes(injection)
  ) {
    throw new Error(`Unknown ERA5_EXPORTER_TEST_INJECTION: ${injection}`);
  }
  return injection;
}

async function main() {
  const { check, all, seeded, out } = parseArgs(process.argv.slice(2));
  assertSafeCustomOut(out);
  assertBuildingPopulation();
  const jobs = plan();
  assertUncommittedPopulation(jobs);
  const promotionJobs = all ? jobs : jobs.filter((job) => job.committed);
  assertSafePlannedDestinations(promotionJobs, out);
  const injection = testInjection();
  const stageDir = mkdtempSync(join(tmpdir(), "era5-building-stage-"));
  const sourceBytes = readFileSync(SOURCE);
  const sourceDigest = createHash("sha256").update(sourceBytes).digest("hex");
  if (sourceDigest !== SOURCE_SHA256) {
    throw new Error(
      `Era 5 source is not the canonical attachment: expected ${SOURCE_SHA256}, got ${sourceDigest}`,
    );
  }
  const kitSource = applyRuntimeComposition(era5KitSource(sourceBytes.toString("utf8")));
  const bundle = threeBundle();
  const testChromiumExecutable =
    process.env.NODE_ENV === "test"
      ? process.env.ERA5_EXPORTER_TEST_CHROMIUM_EXECUTABLE
      : undefined;

  const browser = await chromium.launch(
    testChromiumExecutable ? { executablePath: testChromiumExecutable } : {},
  );
  const problems = [];
  const written = [];

  try {
    const page = await browser.newPage();
    const expectedWarnings = [
      "Use MeshStandardMaterial or MeshBasicMaterial",
      "THREE.Material: 'flatShading' is not a property of THREE.MeshToonMaterial.",
    ];
    page.on("console", (message) => {
      if (
        (message.type() === "error" || message.type() === "warning") &&
        !expectedWarnings.some((warning) => message.text().includes(warning))
      ) {
        problems.push(message.text());
      }
    });
    page.on("pageerror", (error) => problems.push(String(error)));
    await page.setContent("<!doctype html><html><body></body></html>");
    await page.addScriptTag({ path: bundle });
    await page.addScriptTag({ content: kitSource });

    const sourceContract = await page.evaluate(() => {
      const kit = new window.Era5Kit();
      return { keys: Object.keys(kit.defs()), roster: kit.roster(), bare: kit.bare };
    });
    const sourceKeys = sourceContract.keys;
    const expectedKeys = BUILDINGS.map((building) => building.art);
    if (
      sourceKeys.length !== expectedKeys.length ||
      expectedKeys.some((key) => !sourceKeys.includes(key))
    ) {
      throw new Error(
        `attachment defs do not match the ten mapped buildings: ` +
          `source=[${sourceKeys.join(", ")}], mapping=[${expectedKeys.join(", ")}]`,
      );
    }
    if (JSON.stringify(sourceContract.roster) !== JSON.stringify(SOURCE_ROSTER)) {
      throw new Error(
        `attachment roster tuples changed:\n` +
          `expected ${JSON.stringify(SOURCE_ROSTER)}\n` +
          `source   ${JSON.stringify(sourceContract.roster)}`,
      );
    }
    if (sourceContract.bare !== true) {
      throw new Error("Era5Kit no longer defaults to building-only bare mode");
    }

    for (const job of jobs) {
      const result = await page.evaluate(
        async ([art, stage, seed, seeded, fitQuarterTurns]) => {
          const realRandom = Math.random;
          let state = seed >>> 0;
          if (seeded) {
            Math.random = () => {
              state = (state + 0x6d2b79f5) >>> 0;
              let value = state;
              value = Math.imul(value ^ (value >>> 15), value | 1);
              value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
              return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
            };
          }

          const T = window.THREE;
          const managedColour = T.ColorManagement.enabled;
          // Era5Kit calls convertSRGBToLinear itself, as it did under bundled Three r128.
          // Disable r185's implicit conversion for the build so each material converts once.
          T.ColorManagement.enabled = false;
          try {
            const kit = new window.Era5Kit();
            if (kit.bare !== true) {
              throw new Error("Era5Kit no longer defaults to building-only bare mode");
            }
            const build = kit.defs()[art];
            if (!build) {
              throw new Error(`no Era5Kit builder for '${art}'`);
            }
            const group = build(stage);
            group.rotation.y = fitQuarterTurns * (Math.PI / 2);
            group.updateMatrixWorld(true);
            const box = new T.Box3().setFromObject(group);
            const size = box.getSize(new T.Vector3());

            const geometries = new Set();
            const materials = new Set();
            const textures = new Set();
            let meshes = 0;
            let triangles = 0;
            let geometryBytes = 0;
            group.traverse((object) => {
              if (!object.isMesh) {
                return;
              }
              meshes += 1;
              const objectMaterials = Array.isArray(object.material)
                ? object.material
                : [object.material];
              for (const material of objectMaterials) {
                materials.add(material.uuid);
                for (const value of Object.values(material)) {
                  if (value?.isTexture) {
                    textures.add(value.uuid);
                  }
                }
              }
              const geometry = object.geometry;
              if (geometries.has(geometry.uuid)) {
                return;
              }
              geometries.add(geometry.uuid);
              for (const attribute of Object.values(geometry.attributes)) {
                geometryBytes += attribute.array?.byteLength ?? 0;
              }
              if (geometry.index?.array) {
                geometryBytes += geometry.index.array.byteLength;
                triangles += geometry.index.count / 3;
              } else if (geometry.attributes.position) {
                triangles += geometry.attributes.position.count / 3;
              }
            });

            const glb = await new Promise((resolve, reject) =>
              new window.GLTFExporter().parse(group, resolve, reject, { binary: true }),
            );
            let binary = "";
            const bytes = new Uint8Array(glb);
            for (let index = 0; index < bytes.length; index += 1) {
              binary += String.fromCharCode(bytes[index]);
            }
            return {
              b64: btoa(binary),
              min: box.min.toArray().map((value) => Number(value.toFixed(2))),
              max: box.max.toArray().map((value) => Number(value.toFixed(2))),
              size: [size.x, size.y, size.z].map((value) => Number(value.toFixed(2))),
              meshes,
              materials: materials.size,
              textures: textures.size,
              triangles: Math.round(triangles),
              geometryBytes,
            };
          } finally {
            Math.random = realRandom;
            T.ColorManagement.enabled = managedColour;
          }
        },
        [
          job.art,
          job.stage,
          seedFor(job.name.replace(/\.glb$/, "")) ^ (injection === null ? 0 : 0x9e3779b9),
          seeded,
          job.fitQuarterTurns ?? 0,
        ],
      );

      const bytes = Buffer.from(result.b64, "base64");
      writeFileSync(join(stageDir, job.name), bytes, { flag: "wx" });
      written.push({
        ...job,
        bytes: bytes.length,
        min: result.min,
        max: result.max,
        size: result.size,
        meshes: result.meshes,
        materials: result.materials,
        textures: result.textures,
        triangles: result.triangles,
        geometryBytes: result.geometryBytes,
      });
      console.log(
        `${job.name.padEnd(50)} ${String(bytes.length).padStart(9)} B  ` +
          `${result.size.join(" × ")}u  ${String(result.meshes).padStart(4)} meshes  ` +
          `${String(result.materials).padStart(3)} mats  ${String(result.textures).padStart(3)} tex  ` +
          `${String(result.triangles).padStart(7)} tris  ${job.name}`,
      );

      if (injection === "mid-run-error" && written.length === 7) {
        throw new Error("mid-run-error");
      }
    }

    if (injection === "post-run-warning") {
      await page.evaluate(() => console.warn("post-run-warning"));
      await page.waitForTimeout(20);
    }
    if (injection === "post-run-error") {
      const pageError = page.waitForEvent("pageerror");
      await page.evaluate(() => {
        setTimeout(() => {
          throw new Error("post-run-error");
        }, 0);
      });
      // Under a loaded CI runner the timer can fire after a fixed sleep. Await the actual
      // browser event so this safety injection cannot race promotion of the staged outputs.
      await pageError;
    }
  } finally {
    await browser.close();
  }

  if (problems.length > 0) {
    console.error("\nPAGE ERRORS (the export is not trustworthy):");
    for (const problem of problems) {
      console.error(`  ${problem}`);
    }
    throw new Error(`staged export rejected after ${problems.length} page problem(s)`);
  }

  validateStagedOutputs(stageDir, jobs, seeded);
  const total = written.reduce((sum, output) => sum + output.bytes, 0);
  console.log(`\n${written.length} files, ${total} bytes total`);

  if (!check) {
    promoteOutputs(stageDir, promotionJobs, out);
    console.log(
      `${promotionJobs.length} validated output(s) promoted to ${out ?? "the production model tree"}`,
    );
    return;
  }

  console.log(`\n--check: comparing ${stageDir} against the tree`);
  let differing = 0;
  const unchanged = [];
  for (const job of written) {
    const fresh = readFileSync(join(stageDir, job.name));
    const digest = createHash("sha256").update(fresh).digest("hex");
    let tracked = null;
    try {
      tracked = readFileSync(join(job.dir, job.name));
    } catch {
      tracked = null;
    }

    if (!job.committed) {
      if (tracked) {
        console.log(`  ${job.name}: PRESENT in the tree but declared uncommitted`);
        differing += 1;
        continue;
      }
      const same = UNCOMMITTED_DIGESTS[job.name] === digest;
      console.log(
        same
          ? `  ${job.name}: absent by design, regenerates to its pinned digest`
          : `  ${job.name}: absent by design, but REGENERATED DIFFERENTLY ` +
              `(pinned ${UNCOMMITTED_DIGESTS[job.name] || "nothing"}, got ${digest})`,
      );
      if (same) {
        unchanged.push(job.name);
      } else {
        differing += 1;
      }
      continue;
    }

    if (!tracked) {
      console.log(`  ${job.name}: MISSING from the tree`);
      differing += 1;
      continue;
    }
    if (UNCOMMITTED_DIGESTS[job.name]) {
      console.log(`  ${job.name}: committed but also pinned as uncommitted`);
      differing += 1;
      continue;
    }
    const same = fresh.equals(tracked);
    console.log(`  ${job.name}: ${same ? "identical" : "DIFFERS"}`);
    if (same) {
      unchanged.push(job.name);
    } else {
      differing += 1;
    }
  }

  if (seeded) {
    console.log(differing === 0 ? "\nreproducible" : `\n${differing} file(s) differ`);
    process.exitCode = differing === 0 ? 0 : 1;
    return;
  }

  const surprises = unchanged.filter((name) => !SEED_INDEPENDENT.has(name));
  const stale = [...SEED_INDEPENDENT].filter((name) => !unchanged.includes(name));
  console.log(
    `\n--no-seed: ${differing} of ${written.length} differ; ` +
      `${unchanged.length} unchanged (${written.length - SEED_INDEPENDENT.size} expected to differ)`,
  );
  for (const name of surprises) {
    console.log(`  ${name}: UNCHANGED without the seed, and not declared seed-independent`);
  }
  for (const name of stale) {
    console.log(`  ${name}: declared seed-independent but it DIFFERED without the seed`);
  }
  const ok =
    surprises.length === 0 &&
    stale.length === 0 &&
    differing >= written.length - SEED_INDEPENDENT.size;
  console.log(ok ? "the seed is load-bearing" : "the seed claim does not hold");
  process.exitCode = ok ? 0 : 1;
}

await main();
