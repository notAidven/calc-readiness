/** Bundle app Three, GLTFExporter and its own static-geometry merge utility. */
function threeBundle() {
  const dir = mkdtempSync(join(tmpdir(), "era7-three-bundle-"));
  const entry = join(dir, "three-entry.js");
  const exporterModule = join(dir, "GLTFExporter.js");
  const out = join(dir, "three-bundle.js");
  try {
    // Upstream starts every canvas encode/read concurrently, then appends image bufferViews in
    // callback COMPLETION order. The PNG payloads stay identical while their order races, which
    // changes the whole GLB digest. Patch only this disposable bundle copy so image tasks run in
    // processImage invocation order; the exact anchor fails loud on a future Three revision.
    const exporterSource = readFileSync(
      join(ROOT, "node_modules/three/examples/jsm/exporters/GLTFExporter.js"),
      "utf8",
    );
    const unorderedImageTask = `				pending.push(

					getToBlobPromise( canvas, mimeType )
						.then( blob => writer.processBufferViewImage( blob ) )
						.then( bufferViewIndex => {

							imageDef.bufferView = bufferViewIndex;

						} )

				);`;
    const orderedImageTask = `				const previousImageTask = writer.__orderedImageTask || Promise.resolve();
				const imageTask = previousImageTask
					.then( () => getToBlobPromise( canvas, mimeType ) )
					.then( blob => writer.processBufferViewImage( blob ) )
					.then( bufferViewIndex => {

						imageDef.bufferView = bufferViewIndex;

					} );
				writer.__orderedImageTask = imageTask;
				pending.push( imageTask );`;
    const anchor = exporterSource.indexOf(unorderedImageTask);
    if (
      anchor < 0 ||
      exporterSource.indexOf(unorderedImageTask, anchor + unorderedImageTask.length) >= 0
    ) {
      throw new Error(
        "Three GLTFExporter image-order anchor is missing or ambiguous; deterministic image serialization was not applied",
      );
    }
    writeFileSync(
      exporterModule,
      `${exporterSource.slice(0, anchor)}${orderedImageTask}${exporterSource.slice(
        anchor + unorderedImageTask.length,
      )}`,
    );
    writeFileSync(
      entry,
      [
        'import * as THREE from "three";',
        'import { GLTFExporter } from "./GLTFExporter.js";',
        'import { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";',
        "window.THREE = THREE;",
        "window.GLTFExporter = GLTFExporter;",
        "window.mergeGeometries = mergeGeometries;",
        "",
      ].join("\n"),
    );
    const esbuild = join(ROOT, "node_modules/esbuild/bin/esbuild");
    if (!existsSync(esbuild)) {
      throw new Error("esbuild not installed — run `npm install` at the repo root");
    }
    execFileSync(
      process.execPath,
      [
        esbuild,
        entry,
        "--bundle",
        "--format=iife",
        `--outfile=${out}`,
        "--log-level=warning",
      ],
      { env: { ...process.env, NODE_PATH: join(ROOT, "node_modules") } },
    );
    return {
      path: out,
      dispose() {
        rmSync(dir, { recursive: true, force: true });
      },
    };
  } catch (error) {
    rmSync(dir, { recursive: true, force: true });
    throw error;
  }
}

