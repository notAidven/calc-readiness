function exportMetadataBytes(outputs) {
  if (outputs.length !== 33 || new Set(outputs.map((output) => output.name)).size !== 33) {
    throw new Error("Era 7 metadata requires the exact thirty-three generated outputs");
  }
  const rows = outputs.map((output) => ({
    // Metadata is tracked source, so use repository-style separators on every host.
    // Without this, Windows regenerated identical GLBs but reported metadata drift solely
    // because `path.relative` emitted backslashes while the committed JSON uses slashes.
    file: relative(MODELS, join(output.dir, output.name)).replaceAll("\\", "/"),
    kind: output.kind,
    id: output.id,
    art: output.art,
    stage: output.stage,
    committed: output.committed,
    sourceMeshes: output.sourceMeshes,
    shippedMeshes: output.meshes,
    sha256: output.sha256,
  }));
  const built = rows.filter((row) => row.stage === "built");
  const shipping = rows.filter((row) => row.committed);
  const sum = (population, key) =>
    population.reduce((total, output) => total + output[key], 0);
  const document = {
    schema: 1,
    sourceSha256: SOURCE_SHA256,
    generator: "scripts/export-era7-building-models.mjs",
    batching: "world-transform + exact material/index/attribute signature",
    outputs: rows,
    builtSet: {
      count: built.length,
      sourceMeshes: sum(built, "sourceMeshes"),
      shippedMeshes: sum(built, "shippedMeshes"),
    },
    shippingSet: {
      count: shipping.length,
      sourceMeshes: sum(shipping, "sourceMeshes"),
      shippedMeshes: sum(shipping, "shippedMeshes"),
    },
  };
  if (
    document.builtSet.count !== 11 ||
    document.shippingSet.count !== 23 ||
    document.builtSet.sourceMeshes <= document.builtSet.shippedMeshes
  ) {
    throw new Error(
      `Era 7 metadata census is invalid: ${JSON.stringify({
        builtSet: document.builtSet,
        shippingSet: document.shippingSet,
      })}`,
    );
  }
  return Buffer.from(`${JSON.stringify(document, null, 2)}\n`);
}

function validateStagedOutputs(stageDir, jobs, seeded) {
  const expected = jobs.map((job) => job.name).sort();
  const actual = readdirSync(stageDir).sort();
  if (expected.length !== 33 || JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(
      `staged output census is not the exact thirty-three source stages:\n` +
        `expected ${expected.join(", ")}\nactual ${actual.join(", ")}`,
    );
  }

  const digestProblems = [];
  for (const job of jobs) {
    const bytes = readFileSync(join(stageDir, job.name));
    validateGlb(bytes, job.name);
    if (!job.committed) {
      if (lstatOrNull(join(job.dir, job.name)) !== null) {
        throw new Error(`${job.name} is PRESENT in the tree but declared uncommitted`);
      }
      if (seeded) {
        const digest = createHash("sha256").update(bytes).digest("hex");
        if (UNCOMMITTED_DIGESTS[job.name] !== digest) {
          digestProblems.push(
            `${job.name} regenerated differently from its omitted-stage digest: ` +
              `expected ${UNCOMMITTED_DIGESTS[job.name] ?? "nothing"}, got ${digest}`,
          );
        }
      }
    }
  }
  if (digestProblems.length > 0) {
    throw new Error(
      `staged export has ${digestProblems.length} omitted-stage digest mismatch(es):\n` +
        digestProblems.join("\n"),
    );
  }
}

function promoteOutputs(stageDir, jobs, customOut, injection) {
  const token = `${process.pid}-${Date.now()}`;
  const prepared = [];
  const promoted = [];
  try {
    assertSafePlannedDestinations(jobs, customOut);
    for (const job of jobs) {
      const target = promotionTarget(job, customOut);
      mkdirSync(dirname(target), { recursive: true });
      const original = lstatOrNull(target) ? readFileSync(target) : null;
      const next = join(dirname(target), `.${basename(target)}.era7-next-${token}`);
      if (lstatOrNull(next) !== null) {
        throw new Error(`Exporter promotion temp already exists: ${next}`);
      }
      writeFileSync(next, readFileSync(join(stageDir, job.name)), { flag: "wx" });
      prepared.push({ target, next, original });
    }
    for (const item of prepared) {
      renameSync(item.next, item.target);
      promoted.push(item);
      const promotionFailure = /^mid-promotion-error:(\d+)$/.exec(injection ?? "");
      if (
        promotionFailure &&
        promoted.length === Number.parseInt(promotionFailure[1] ?? "", 10)
      ) {
        throw new Error(injection);
      }
    }
  } catch (error) {
    for (const item of prepared) {
      if (lstatOrNull(item.next) !== null) unlinkSync(item.next);
    }
    for (const item of [...promoted].reverse()) {
      if (item.original === null) {
        if (lstatOrNull(item.target) !== null) unlinkSync(item.target);
        continue;
      }
      const rollback = join(
        dirname(item.target),
        `.${basename(item.target)}.era7-rollback-${token}`,
      );
      writeFileSync(rollback, item.original, { flag: "wx" });
      renameSync(rollback, item.target);
    }
    throw error;
  }
}

